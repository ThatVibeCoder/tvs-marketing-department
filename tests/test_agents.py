"""Every coding agent gets the same rules and the same commands. Run: python3 -m unittest discover tests

AGENTS.md is the one rules file. sync.py writes CLAUDE.md, GEMINI.md and the Cursor rule as short pointers to
it, and every team, workflow and skill as a command for Gemini CLI and Cursor next to the Claude and Codex skills.
"""
import os
import shutil
import subprocess
import sys
import tempfile
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MARK = "generated by tools/sync.py from AGENTS.md"


def read(p):
    with open(p, encoding="utf-8") as f:
        return f.read()


class AgentFilesTest(unittest.TestCase):
    def test_pointers_point_and_never_copy_the_rules(self):
        for rel in ("CLAUDE.md", "GEMINI.md", ".cursor/rules/agents.mdc"):
            text = read(os.path.join(ROOT, rel))
            self.assertIn(MARK, text, rel)
            self.assertIn("AGENTS.md", text, rel)
            self.assertLess(len(text), 900, f"{rel} should be a short pointer, not a copy of the rules")
            self.assertNotIn("## Where everything goes", text, rel)
        self.assertIn("@AGENTS.md", read(os.path.join(ROOT, "CLAUDE.md")))
        self.assertIn("@AGENTS.md", read(os.path.join(ROOT, "GEMINI.md")))
        self.assertIn("alwaysApply: true", read(os.path.join(ROOT, ".cursor/rules/agents.mdc")))

    def test_every_shortcut_is_a_command_everywhere(self):
        skills = sorted(os.listdir(os.path.join(ROOT, ".claude", "skills")))
        self.assertEqual(skills, sorted(os.listdir(os.path.join(ROOT, ".agents", "skills"))))
        gemini = sorted(f[:-5] for f in os.listdir(os.path.join(ROOT, ".gemini", "commands")) if f.endswith(".toml"))
        cursor = sorted(f[:-3] for f in os.listdir(os.path.join(ROOT, ".cursor", "commands")) if f.endswith(".md"))
        self.assertEqual(skills, gemini)
        self.assertEqual(skills, cursor)

    def test_gemini_commands_are_valid_toml(self):
        try:
            import tomllib
        except ImportError:
            self.skipTest("tomllib needs Python 3.11+")
        d = os.path.join(ROOT, ".gemini", "commands")
        for f in os.listdir(d):
            with open(os.path.join(d, f), "rb") as fh:
                data = tomllib.load(fh)
            self.assertTrue(data["description"] and data["prompt"], f)


class AgentSyncTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.repo = os.path.join(self.tmp, "repo")
        shutil.copytree(ROOT, self.repo, ignore=shutil.ignore_patterns(".git", "__pycache__", ".env"))

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def sync(self, *args):
        r = subprocess.run([sys.executable, "tools/sync.py", *args], cwd=self.repo, capture_output=True, text=True, encoding="utf-8")
        return r.returncode, r.stdout + r.stderr

    def test_a_new_skill_reaches_every_agent_and_a_removed_one_leaves(self):
        skill = os.path.join(self.repo, "departments/example/example-team/example-member/skills/test-the-agents")
        os.makedirs(skill)
        with open(os.path.join(skill, "SKILL.md"), "w", encoding="utf-8") as f:
            f.write("---\nname: test-the-agents\ndescription: A skill made by a test.\n---\n# test\n")
        code, out = self.sync()
        self.assertEqual(code, 0, out)
        for rel in (".claude/skills/test-the-agents/SKILL.md", ".agents/skills/test-the-agents/SKILL.md",
                    ".gemini/commands/test-the-agents.toml", ".cursor/commands/test-the-agents.md"):
            self.assertTrue(os.path.exists(os.path.join(self.repo, rel)), rel)
        shutil.rmtree(skill)
        code, out = self.sync()
        self.assertEqual(code, 0, out)
        self.assertFalse(os.path.exists(os.path.join(self.repo, ".gemini/commands/test-the-agents.toml")))
        self.assertFalse(os.path.exists(os.path.join(self.repo, ".cursor/commands/test-the-agents.md")))

    def test_check_catches_an_edited_pointer(self):
        with open(os.path.join(self.repo, "GEMINI.md"), "a", encoding="utf-8") as f:
            f.write("\nextra rules written here by hand\n")
        code, out = self.sync("--check")
        self.assertEqual(code, 1, out)
        self.assertIn("GEMINI.md", out)


if __name__ == "__main__":
    unittest.main()
