ICON_FOR = [("approve", "check"), ("plan", "form"), ("save", "db"), ("ship", "send"), ("live", "send"),
            ("test", "check"), ("security", "shield"), ("sweep", "shield"), ("read", "search"), ("check", "search"),
            ("write", "form"), ("draft", "form"), ("key", "shield"), ("report", "log"), ("research", "search")]


def icon(text):
    t = text.lower()
    for k, v in ICON_FOR:
        if k in t:
            return v
    return "sparkle"


def build_cc(depts, today):
    teams = []
    for d in depts:
        for t in d["teams"]:
            seats = [{"name": m["name"], "type": m["status"].title(), "detail": m["desc"]} for m in t["members"]]
            skills = [{"name": s["name"], "command": "/" + s["name"], "seat": m["name"], "owns": s["description"][:160]}
                      for m in t["members"] for s in m["skills"]]
            for w in t["workflows"]:
                skills.append({"name": slug(w["say"]), "command": "/" + slug(w["say"]), "seat": "Workflow",
                               "owns": f"Say \"{w['say']}\". " + (w["when"] or "")})
            phases, nodes, edges = [], [], []
            for wi, w in enumerate(t["workflows"]):
                prefix = f"w{wi}-"
                for pi, ph in enumerate(w["phases"]):
                    label = ph if len(t["workflows"]) == 1 else f"{w['say']} · {ph}"
                    phases.append({"id": prefix + slug(ph), "label": label, "color": COLORS[(pi + wi) % len(COLORS)]})
                prev = None
                for i, st in enumerate(w["steps"]):
                    nid = f"{prefix}s{i + 1}"
                    nodes.append({"id": nid, "phase": prefix + slug(st["phase"]), "label": st["member"],
                                  "sub": (st["skill"] or st["text"])[:48], "icon": "check" if st["gate"] else icon(st["text"]),
                                  **({"badge": "gate"} if st["gate"] else {}), "detail": st["text"]})
                    if prev:
                        edges.append({"from": prev, "to": nid})
                    prev = nid
            teams.append({"id": t["id"], "name": t["name"], "command": t["command"], "department": d["id"],
                          "departmentName": d["name"], "teamType": d["name"],
                          "buildStatus": "active" if t["status"] == "live" else "planning", "purpose": t["purpose"],
                          "sourceOfTruth": t["path"], "flowAsOf": today, "seats": seats, "skills": skills,
                          "flow": {"phases": phases, "nodes": nodes, "edges": edges}})
    autos = []
    rdir = os.path.join(ROOT, "routines")
    for r in sorted(os.listdir(rdir)) if os.path.isdir(rdir) else []:
        p = os.path.join(rdir, r, "README.md")
        if not os.path.isfile(p):
            continue
        meta, body = frontmatter(read(p))
        title = re.search(r"^# (.+)$", body, re.M)
        sched = meta.get("schedule", "")
        for k, v in meta.get("__raw__", {}).items():
            if not yaml_safe(v):
                errors.append(f"{rel(p)}: the `{k}:` line has ': ' in it; wrap the value in double quotes")
        status = meta.get("status", "planned")
        if status not in ("planned", "live"):
            errors.append(f"{rel(p)}: `status:` must be `planned` or `live`")
        autos.append({"id": r, "name": meta.get("name") or (title.group(1) if title else r),
                      "description": meta.get("purpose", first_paragraph(body)), "area": meta.get("team", "routines"),
                      "trigger": {"type": "cron" if sched else "manual", "schedule": sched or "not scheduled yet"},
                      "active": status == "live", "sourceOfTruth": rel(p),
                      "stats": {"lastRunAt": None, "lastRunStatus": None, "runCount": None, "failureCount": None,
                                "failureRate": None, "avgRunMs": None, "extras": []},
                      "flow": {"topologySource": rel(p), "nodes": [], "edges": []}})
    return {"teams.json": teams, "automations.json": autos}


def sync_cc(data, check):
    stale = []
    ex = os.path.join(CC_DATA, "executions.json")
    executions = json.loads(read(ex)) if os.path.exists(ex) else []
    files = {k: json.dumps(v, indent=2, ensure_ascii=False) + "\n" for k, v in data.items()}
    if not os.path.exists(ex):
        files["executions.json"] = "[]\n"
    files["data.js"] = ("// generated by tools/sync.py so the dashboard opens straight from the folder. Do not edit.\n"
                        "window.CC_DATA = " + json.dumps({"teams": data["teams.json"], "automations": data["automations.json"],
                                                          "executions": executions}, ensure_ascii=False) + ";\n")

    def strip_dates(s):
        return re.sub(r'"flowAsOf": ?"[0-9-]+"', "", s)
    for name, text in files.items():
        p = os.path.join(CC_DATA, name)
        old = read(p) if os.path.exists(p) else None
        if old is None or strip_dates(old) != strip_dates(text):
            stale.append(rel(p))
            if not check:
                write(p, text)
    return stale


def main():
    check = "--check" in sys.argv
    today = datetime.date.today().isoformat()
    depts = read_tree()
    validate(depts)
    shortcuts = build_shortcuts(depts)
    data = build_cc(depts, today)
    # look first, write only if nothing is broken
    stale = sync_shortcuts(shortcuts, check=True) + sync_cc(data, check=True)
    if not check and not errors:
        stale = sync_shortcuts(shortcuts, check=False) + sync_cc(data, check=False)
    n_t = sum(len(d["teams"]) for d in depts)
    n_m = sum(len(t["members"]) for d in depts for t in d["teams"])
    n_w = sum(len(t["workflows"]) for d in depts for t in d["teams"])
    print(f"{len(depts)} departments · {n_t} teams · {n_m} team members · {len(all_skills(depts))} skills · {n_w} workflows")
    for w in dict.fromkeys(warnings):
        print("NOTE:", w)
    for e in dict.fromkeys(errors):
        print("FIX:", e)
    if check:
        for s in stale:
            print("OUT OF DATE:", s)
        if errors or stale:
            print("Not in sync. Fix anything marked FIX, then run `python3 tools/sync.py`.")
            sys.exit(1)
        print("Everything is in sync.")
    else:
        if errors:
            print("Nothing was rebuilt. Fix the lines marked FIX, then run this again.")
            sys.exit(1)
        print(f"Rebuilt {len(stale)} file(s)." if stale else "Already in sync. Nothing changed.")


if __name__ == "__main__":
    main()
