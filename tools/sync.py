def toml_str(s):
    return json.dumps(s)  # a JSON string is a valid TOML basic string


def agent_command_files():
    files = {}
    for name, (desc, body, real) in sorted(SHORTCUT_META.items()):
        prompt = f"{body}\n\nThe real file is `{real}`. Follow AGENTS.md. Anything the owner typed after the command: {{{{args}}}}"
        files[f".gemini/commands/{name}.toml"] = f"# {AGENT_MARK}\ndescription = {toml_str(desc)}\nprompt = {toml_str(prompt)}\n"
        files[f".cursor/commands/{name}.md"] = f"<!-- {AGENT_MARK} -->\n{body}\n\nThe real file is `{real}`. Follow AGENTS.md.\n"
    return files


def sync_agent_files(check):
    want = {**agent_entry_files(), **agent_command_files()}
    stale = []
    for d, ext in COMMAND_DIRS.items():
        base = os.path.join(ROOT, d)
        for f in sorted(os.listdir(base)) if os.path.isdir(base) else []:
            rp = f"{d}/{f}"
            if f.endswith(ext) and rp not in want and AGENT_MARK in read(os.path.join(base, f)):
                stale.append(f"{rp} (no longer exists)")
                if not check:
                    os.remove(os.path.join(base, f))
    for rp, text in want.items():
        p = os.path.join(ROOT, rp)
        old = read(p) if os.path.exists(p) else None
        if old is not None and AGENT_MARK not in old and rp not in ("CLAUDE.md",):
            warnings.append(f"{rp} was written by hand, so it was left alone. Delete it and run sync to get the generated one.")
            continue
        if old != text:
            stale.append(rp)
            if not check:
                write(p, text)
    return stale


