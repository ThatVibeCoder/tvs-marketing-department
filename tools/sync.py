def rel(p):
    return os.path.relpath(p, ROOT).replace(os.sep, "/")  # same paths on Windows, Mac and Linux


def read(p):
    with open(p, encoding="utf-8") as f:
        return f.read()


def write(p, text, mode=None):
    """Write a whole file at once: into a temp file next to it, then swapped in, so a crash (or an AI reading at
    that moment) never sees half a file. mode=0o600 keeps a file private to you (.env)."""
    import tempfile
    d = os.path.dirname(p)
    os.makedirs(d, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=d, prefix="." + os.path.basename(p) + ".", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as f:
            f.write(text)
        if mode is None:  # mkstemp makes the temp file 0600: give it the old file's mode, or the usual one for a new file
            if os.path.exists(p):
                mode = os.stat(p).st_mode & 0o777
            else:
                um = os.umask(0); os.umask(um)
                mode = 0o666 & ~um
        os.chmod(tmp, mode)
        os.replace(tmp, p)
    except BaseException:
        if os.path.exists(tmp):
            os.remove(tmp)
        raise


def frontmatter(text):
    """Simple `key: value` frontmatter between --- lines. Values may be wrapped in quotes. Returns (dict, body)."""
    # A doc pasted from Google Docs often carries blank lines (or an invisible BOM) above the first ---.
    # They change nothing, so skip them instead of failing with "needs a name: and a description:".
    text = text.lstrip("\ufeff \t\r\n")
    if not text.startswith("---"):
        return {}, text
    end = text.find("\n---", 3)
    if end < 0:
        return {}, text
    meta, raw = {}, {}
    for line in text[3:end].strip().splitlines():
        if ":" in line and not line.startswith((" ", "\t")):
            k, v = line.split(":", 1)
            v = v.strip()
            raw[k.strip()] = v
            if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
                try:
                    v = json.loads(v) if v[0] == '"' else v[1:-1]
                except ValueError:
                    v = v[1:-1]
            meta[k.strip()] = v
    meta["__raw__"] = raw
    return meta, text[end + 4:].lstrip("\n")


def yaml_safe(raw_value):
    """True if a value is safe in strict YAML: quoted, or free of ': ', ' #' and a leading special character."""
    v = raw_value.strip()
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
        return True
    return ": " not in v and " #" not in v and v[:1] not in set("[]{}&*!|>%@`'\"")


def first_paragraph(body):
    for block in re.split(r"\n\s*\n", body):
        b = block.strip()
        if b and not b.startswith(("#", "**Status", "**Team", "Before any job", "---", "```")):
            return re.sub(r"\s+", " ", b)
    return ""


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def section_text(body, title):
    m = re.search(r"^## " + re.escape(title) + r"\s*$(.*?)(?=^## |\Z)", body, re.M | re.S)
    return m.group(1) if m else ""


# ---------- read the tree ----------
def read_skill(path, owner):
    meta, _ = frontmatter(read(path))
    folder = os.path.basename(os.path.dirname(path))
    name, desc = meta.get("name", ""), meta.get("description", "")
    raw = meta.get("__raw__", {})
    if not name or not desc:
        errors.append(f"{rel(path)}: needs a `name:` and a `description:` at the top")
    elif name != folder:
        errors.append(f"{rel(path)}: name `{name}` must match its folder `{folder}`")
    if desc and not yaml_safe(raw.get("description", "")):
        errors.append(f"{rel(path)}: the description has ': ' or another special character in it, so Codex can't read it. "
                      f"Wrap the whole description in double quotes, or reword it.")
    if len(desc) > MAX_DESC:
        errors.append(f"{rel(path)}: the description is {len(desc)} characters; keep it under {MAX_DESC}")
    return {"name": name or folder, "description": desc, "path": rel(path), "owner": owner}


def member_aliases(folder, title, body):
    """Every name a workflow step may use for this team member, lowercased. Lessons invite owners to name a
    team member ("Copywriter (Paige)", or just "Paige"), so the role name the workflows use must keep working:
    the folder's role name, the full title, the title without a nickname, and a `**Name:**` line."""
    names = {folder.replace("-", " "), title}
    names.add(re.sub(r"\s*[(\[\"\u201c].*$", "", title))          # Copywriter ("Paige") -> Copywriter
    names.add(re.split(r"\s+[-\u2013\u2014:,]\s+", title)[0])        # Copywriter - Paige -> Copywriter
    nick = re.search(r"^\*\*Name:\*\*\s*(.+)$", body, re.M)
    if nick:
        names.add(nick.group(1).strip())
    return {n.strip().lower() for n in names if n.strip()}


def read_member(team_dir, folder, team):
    path = os.path.join(team_dir, folder, folder + ".md")
    if not os.path.exists(path):
        return None
    body = read(path)
    title = re.search(r"^# (.+)$", body, re.M)
    status = re.search(r"^\*\*Status:\*\*\s*(\S+)", body, re.M)
    st = status.group(1).strip().rstrip(".").lower() if status else ""
    if st not in ("seeded", "live"):
        errors.append(f"{rel(path)}: needs `**Status:** seeded` or `**Status:** live` under the title"
                      + (f" (found `{st}`; a version-2 `staffed` means `live`)" if st else ""))
    if not re.search(r"^\*\*Team:\*\*\s*\S", body, re.M):
        errors.append(f"{rel(path)}: needs a `**Team:** {team['name']}` line under the Status line")
    old = next((o for o in OLD_READ_LINES if o in body), None)
    if READ_LINE not in body and old:
        old_read_lines.append((path, old))
    elif READ_LINE not in body:
        errors.append(f"{rel(path)}: needs the read-first line from AGENTS.md: \"{READ_LINE}\"")
    m = {"id": folder, "name": title.group(1).strip() if title else folder.replace("-", " ").title(),
         "status": st or "seeded", "path": rel(path), "desc": first_paragraph(body), "team": team, "skills": []}
    m["aliases"] = member_aliases(folder, m["name"], body)
    sk = os.path.join(team_dir, folder, "skills")
    if os.path.isdir(sk):
        for s in sorted(os.listdir(sk)):
            p = os.path.join(sk, s, "SKILL.md")
            if os.path.exists(p):
                m["skills"].append(read_skill(p, m))
            elif os.path.isdir(os.path.join(sk, s)):
                errors.append(f"{rel(os.path.join(sk, s))}: a skill folder needs a SKILL.md inside it")
    return m


# a step is `1. **Member** · skill-name · what happens`, or `1. **Member** what happens` when no skill runs
STEP = re.compile(r"^\s*(\d+)\.\s+\*\*(.+?)\*\*\s*(.*)$")
SKILL_IN_STEP = re.compile(r"^·\s*`?([a-z0-9][a-z0-9-]*)`?\s+·\s*(.*)$")


def read_workflows(body, tpath):
    flows = []
    for m in re.finditer(r"^## Workflow:\s*(.+?)\s*$(.*?)(?=^## |\Z)", body, re.M | re.S):
        name, text = m.group(1).strip(), m.group(2)
        say = re.search(r'^Say:\s*"(.+?)"', text, re.M)
        also = re.search(r"^Also say:\s*(.+)$", text, re.M)
        when = re.search(r"^When:\s*(.+)$", text, re.M)
        phases, steps, cur = [], [], None
        for line in text.splitlines():
            ph = re.match(r"^###\s+(.+)$", line)
            if ph:
                cur = ph.group(1).strip()
                phases.append(cur)
                continue
            st = STEP.match(line)
            if not st:
                continue
            if not cur:
                errors.append(f"{tpath}: workflow '{name}' has a numbered step before its first ### phase: {line.strip()[:60]}")
                continue
            rest = st.group(3).strip()
            sk = SKILL_IN_STEP.match(rest)
            skill, what = (sk.group(1), sk.group(2)) if sk else ("", rest.lstrip("· ").strip())
            steps.append({"n": len(steps) + 1, "member": st.group(2).strip(), "skill": skill,
                          "text": what.replace("[you approve]", "").strip(), "gate": "[you approve]" in rest,
                          "phase": cur})
        flows.append({"name": name, "say": say.group(1) if say else name, "also": also.group(1).strip() if also else "",
                      "when": when.group(1) if when else "", "phases": phases, "steps": steps})
    return flows


def read_members_list(body):
    """`- **Name** (`folder/`)` lines under ## Members. A line with (optional) may not exist yet."""
    out = []
    for line in section_text(body, "Members").splitlines():
        mm = re.match(r"^\s*-\s.*?\*\*(.+?)\*\*\s*\(`([a-z0-9-]+)/`\)", line)
        if mm:
            out.append({"name": mm.group(1), "folder": mm.group(2), "optional": "(optional)" in line})
    return out


def read_tree():
    depts = []
    for d in sorted(os.listdir(DEPTS)):
        ddir = os.path.join(DEPTS, d)
        if not os.path.isdir(ddir):
            continue
        readme = os.path.join(ddir, "README.md")
        dmeta = frontmatter(read(readme))[0] if os.path.exists(readme) else {}
        if not dmeta.get("name"):
            errors.append(f"{rel(ddir)}: needs a README.md with `name:` and `purpose:` at the top")
        for k, v in dmeta.get("__raw__", {}).items():
            if not yaml_safe(v):
                errors.append(f"{rel(readme)}: the `{k}:` line has ': ' in it; wrap the value in double quotes")
        dept = {"id": d, "name": dmeta.get("name", d.replace("-", " ").title()), "purpose": dmeta.get("purpose", ""), "teams": []}
        for t in sorted(os.listdir(ddir)):
            tdir = os.path.join(ddir, t)
            if not os.path.isdir(tdir):
                continue
            tpath = os.path.join(tdir, "team.md")
            if not os.path.isfile(tpath):
                errors.append(f"{rel(tdir)}: a team folder needs a team.md. Teams come from their classroom lesson; if this folder was made by hand to hold a file, move the file to its home in AGENTS.md and delete the folder")
                continue
            meta, body = frontmatter(read(tpath))
            for k in ("name", "command", "department", "status", "purpose"):
                if not meta.get(k):
                    errors.append(f"{rel(tpath)}: the header needs `{k}:`")
            if meta.get("command") and meta["command"] != "/" + t:
                errors.append(f"{rel(tpath)}: `command:` should be `/{t}` (the folder name)")
            if meta.get("status") and meta["status"] not in ("seeded", "live"):
                errors.append(f"{rel(tpath)}: `status:` must be `seeded` or `live`")
            if meta.get("department") and meta["department"] != dept["name"]:
                errors.append(f"{rel(tpath)}: `department:` should be `{dept['name']}` (from {d}/README.md)")
            for k, v in meta.get("__raw__", {}).items():
                if not yaml_safe(v):
                    errors.append(f"{rel(tpath)}: the `{k}:` line has ': ' in it; wrap the value in double quotes")
            team = {"id": t, "name": meta.get("name", t), "command": "/" + t, "status": meta.get("status", "seeded"),
                    "purpose": meta.get("purpose", ""), "dept": dept, "path": rel(tpath),
                    "workflows": read_workflows(body, rel(tpath)), "members": [], "listed": read_members_list(body)}
            for f in sorted(os.listdir(tdir)):
                if os.path.isdir(os.path.join(tdir, f)):
                    mem = read_member(tdir, f, team)
                    if mem:
                        team["members"].append(mem)
                    else:
                        errors.append(f"{rel(os.path.join(tdir, f))}: a team member folder needs {f}.md inside it")
            dept["teams"].append(team)
        depts.append(dept)
    return depts


def all_skills(depts):
    return [s for d in depts for t in d["teams"] for m in t["members"] for s in m["skills"]]


def validate(depts):
    names = {s["name"] for s in all_skills(depts)}
    member_names = {a for d in depts for t in d["teams"] for m in t["members"] for a in m["aliases"]} | {"you"}
    ids = {}

    def claim(i, what):
        if i in ids:
            errors.append(f"the command `/{i}` is claimed twice: {ids[i]} and {what}. Rename one so each command is unique.")
        else:
            ids[i] = what
    for d in depts:
        for t in d["teams"]:
            claim(t["id"], f"team {t['path']}")
            folders = {m["id"] for m in t["members"]}
            for li in t["listed"]:
                if li["folder"] not in folders and not li["optional"]:
                    errors.append(f"{t['path']}: Members lists `{li['folder']}/`, but that folder doesn't exist "
                                  f"(make it, or mark the line (optional))")
            for f in sorted(folders - {li["folder"] for li in t["listed"]}):
                errors.append(f"{t['path']}: team member `{f}/` exists but isn't in the ## Members list")
            for w in t["workflows"]:
                claim(slug(w["say"]), f"workflow \"{w['say']}\" in {t['path']}")
                if not w["steps"]:
                    errors.append(f"{t['path']}: workflow '{w['name']}' has no numbered steps under a ### phase")
                for st in w["steps"]:
                    if st["member"].lower() not in member_names:
                        # Lessons build teams one at a time, and a workflow may hand a step to a team member whose
                        # team's lesson hasn't happened yet. That's a note, not a stop; a typo reads the same way.
                        warnings.append(f"{t['path']}: workflow '{w['name']}' step {st['n']} is done by "
                                        f"`{st['member']}`, who isn't on any team in departments/ yet. If a later lesson "
                                        f"builds that team member, the step is skipped until then; if it's a typo, fix the name")
                    if st["skill"] and st["skill"] not in names:
                        warnings.append(f"{t['path']}: workflow '{w['name']}' step {st['n']} uses skill `{st['skill']}`, "
                                        f"which isn't installed yet (a classroom lesson adds it)")
            for m in t["members"]:
                for s in m["skills"]:
                    claim(s["name"], f"skill {s['path']}")


# ---------- 1. skill shortcuts ----------
SHORTCUT_META = {}  # name -> (description, body, real file), reused for the other agents' command files


def shortcut(name, desc, body, real):
    SHORTCUT_META[name] = (re.sub(r"\s+", " ", desc).strip(), body.strip(), real)
    desc = re.sub(r"\s+", " ", desc).strip()
    if len(desc) > MAX_DESC:
        desc = desc[:MAX_DESC - 3].rsplit(" ", 1)[0] + "..."
    return f"---\nname: {name}\ndescription: {json.dumps(desc, ensure_ascii=False)}\n---\n{MARK}{real} -->\n\n{body.strip()}\n"


def build_shortcuts(depts):
    out = {}
    for d in depts:
        for t in d["teams"]:
            wf = "; ".join(f'"{w["say"]}"' for w in t["workflows"]) or "none yet"
            desc = (f"Summon the {t['name']} ({d['name']}). {t['purpose']} Runs its workflows ({wf}) or any single skill "
                    f"of its team members. Use when the owner says {t['command']}, {t['name'].lower()}, "
                    f"summon my {t['name'].lower()}, or names one of its workflows.")
            body = (f"# {t['name']}\n\nYou are summoning the {t['name']}. The real instructions live in `{t['path']}`.\n\n"
                    f"1. Read `{t['path']}` in full. Read other files only when the step you run names them.\n"
                    f"2. If the owner named a workflow, run it exactly as `team.md` writes it (\"Running a workflow\" in AGENTS.md).\n"
                    f"3. If they didn't, show the menu: each workflow in one plain line, then each team member with its "
                    f"single skills. Ask which one, then run it.\n"
                    f"4. Each step acts as the named team member: read that member's file first and stay inside its edges.")
            out[t["id"]] = shortcut(t["id"], desc, body, t["path"])
            for w in t["workflows"]:
                wid = slug(w["say"])
                extra = f" Also when they say {w['also']}." if w["also"] else ""
                desc = f"Run the {t['name']}'s \"{w['say']}\" workflow, start to finish. {w['when']} Use when the owner says \"{w['say']}\".{extra}"
                body = (f"# {w['say']}\n\nThis is a workflow of the {t['name']}. Read `{t['path']}`, find "
                        f"\"## Workflow: {w['name']}\", and run it as \"Running a workflow\" in AGENTS.md says: each step "
                        f"acts as its team member (read their file first), a step with a skill runs that skill, and every "
                        f"step marked you approve waits for the owner's yes.")
                out[wid] = shortcut(wid, desc, body, t["path"])
            for m in t["members"]:
                for s in m["skills"]:
                    body = (f"# {s['name']}\n\nThis skill belongs to the {m['name']} on the {t['name']}.\n\n"
                            f"1. Read `{m['path']}` first and act as that team member, inside its edges.\n"
                            f"2. Read `{s['path']}` and follow it exactly. That file is the real skill.")
                    out[s["name"]] = shortcut(s["name"], s["description"], body, s["path"])
    return out


def sync_shortcuts(shortcuts, check):
    stale = []
    for sd in SKILL_DIRS:
        base = os.path.join(ROOT, sd)
        existing = {}
        for n in (sorted(os.listdir(base)) if os.path.isdir(base) else []):
            p = os.path.join(base, n, "SKILL.md")
            if os.path.isfile(p):
                existing[n] = read(p)
            elif os.path.isdir(os.path.join(base, n)):
                errors.append(f"{sd}/{n}: a folder with no SKILL.md. Move anything in it into departments/, then delete it.")
        for n, text in existing.items():
            if MARK not in text:
                errors.append(f"{sd}/{n}: this skill was saved straight into {sd}/, so the other AI tool can't see it. "
                              f"Move it to the team member that owns it (departments/<department>/<team>/<member>/skills/{n}/SKILL.md), "
                              f"delete {sd}/{n}/, then run sync again. (An old version-2 copy: just delete the folder.)")
            elif n not in shortcuts:
                stale.append(f"{sd}/{n} (no longer exists)")
                if not check:
                    folder = os.path.join(base, n)
                    os.remove(os.path.join(folder, "SKILL.md"))
                    if os.listdir(folder):
                        warnings.append(f"{sd}/{n}/ still has other files in it; they were left alone. Move them into departments/.")
                    else:
                        os.rmdir(folder)
        for n, text in shortcuts.items():
            if n in existing and MARK not in existing[n]:
                continue
            if existing.get(n) != text:
                stale.append(f"{sd}/{n}")
                if not check:
                    write(os.path.join(base, n, "SKILL.md"), text)
    return stale


def sync_member_lines(check):
    """Swap an old read-first line in a team member file for READ_LINE (the file's only generated line)."""
    stale = []
    for path, old in old_read_lines:
        stale.append(f"{rel(path)} (old read-first line)")
        if not check:
            write(path, read(path).replace(old, READ_LINE))
    return stale


