"""Keep this department in sync with itself.

Run it after anything is added, renamed or removed (a team, a team member, a skill, a workflow, a routine),
and before every save. From the real folders, it:

  1. Checks the structure, and prints FIX for anything broken (a team's header, a team member's Status,
     Team and read-first lines, a skill's name and description, workflow steps, name clashes,
     a skill saved in the wrong place).
  2. Rebuilds the shortcuts in .claude/skills/ (Claude Code) and .agents/skills/ (Codex), the same files in
     both: one per team (/dev-team), one per workflow (/ship-my-landing-page), one per team member
     skill (/save-work). The real files stay inside departments/.
  3. Rebuilds the Command Center data (command-center/data/) so the dashboard shows every team,
     workflow, team member, skill and routine.
  4. If command-center/data/payments.json is there (the Payments Agent fills it), checks it and copies it to
     payments.js so the Dashboard can show your revenue. Both files stay on this computer.

  python3 tools/sync.py           rebuild everything (Mac and Linux)
  py tools/sync.py                the same on Windows (or: python tools/sync.py)
  ... --check                     change nothing; exit 1 if anything is out of date or broken

Standard library only. Works the same for Claude Code and Codex.
"""
